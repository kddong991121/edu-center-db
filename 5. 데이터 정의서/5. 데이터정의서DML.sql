-- 전체 과정(1~34번, 모집중 제외) 출결 데이터 (약 11만개)
insert into TBLATTENDANCE (attendanceNumber, attendanceDate, attendanceType, studentNumber)
select
    ROWNUM as attendanceNumber,
    d.attDate,
    CASE
        WHEN MOD(ROWNUM, 20) = 0 THEN '결석'
        WHEN MOD(ROWNUM, 13) = 0 THEN '지각'
        ELSE '출석'
    END as attendanceType,
    st.studentNumber
from
    (
        select courseNumber,
               courseStartDate,
               LEAST(courseEndDate, TRUNC(SYSDATE)) as attEndDate,
               MOD(courseNumber - 1, 6) as grp
        from tblCourse
        where courseStartDate <= TRUNC(SYSDATE)   -- 모집중(35,36)은 자동 제외
    ) c,
    (
        select studentNumber, MOD(TRUNC((studentNumber - 1) / 28), 6) as grp
        from tblStudent
    ) st,
    lateral (
        select c.courseStartDate + LEVEL - 1 as attDate
        from dual
        connect by LEVEL <= (c.attEndDate - c.courseStartDate + 1)
    ) d
where st.grp = c.grp
  and MOD(d.attDate - DATE '2001-01-01', 7) <= 4   -- 평일만
order by st.studentNumber, d.attDate;

